                        <p>Modern dental techniques make it possible to perform the implant placement procedure
                            painlessly and comfortably. Concerned patients may also request sedation from the dentist to
                            feel at ease during the placement of a dental implant.

                            Initially, minor surgery is made to expose the bone and the bone is drilled deep to place
                            the titanium implant.
                            In situations, where the bone is too weak or not strong enough to support implant surgery,
                            the doctor may recommend bone grafting.
