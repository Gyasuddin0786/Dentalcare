                <h5>1. Dental implants</h5>
                <p>A dental implant is essentially a titanium post that is surgically inserted into the jawbone below
                    the
                    gum line. Then the implantologist will place a crown on top of the surgically inserted Titanium
                    implant
                    To ensure that it looks like a natural tooth.</p>
                <h5>2. Crowns & bridges</h5>
                <p>Crowns and most bridges are both fixed prosthetic devices. Unlike removable devices such as dentures,
                    which can be removed and cleaned on a daily basis, crowns and bridges are cemented onto existing
                    teeth
                    or implants and can only be removed by a dentist.</p>
                <ol>
                    <b>
                        <li>How do Crowns Work?</li>
                    </b>
                    <p>A crown is a dental restoration that completely covers or “caps” a damaged tooth. A crown can be
                        used
                        to improve the appearance, shape, or alignment of a damaged tooth in addition to strengthening
                        it.
                    </p>
                    <b>
                        <li>How do Bridges Work?</li>
                    </b>
                    <p>If your mouth is missing one or more teeth, a bridge may be recommended. Missing teeth leave gaps
                        that eventually cause the remaining teeth to rotate or shift into empty spaces, resulting in a
                        bad
                        bite. Gum disease and temporomandibular joint (TMJ) disorders can result from the imbalance
                        caused
                        by missing teeth</p>
                    </ol>
                <h5>3. Dentures</h5>
                <p>A denture is a removable viable substitute for missing teeth and gums. complete dentures and partial
                    dentures are the two types of Dentures available. When all the teeth are lost, complete dentures are
                    used, whereas partial dentures are used if some natural teeth remain.
                    
                    These treatments and also other treatments like inlays & Onlays, Veneers, Teeth-whitening, and
